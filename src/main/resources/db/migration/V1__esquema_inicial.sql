-- =====================================================================
-- Conta Litro - esquema inicial
-- Compativel com PostgreSQL (producao) e H2 em modo PostgreSQL (dev/teste).
-- O Flyway e o dono do esquema: o Hibernate so VALIDA, nunca altera.
-- =====================================================================

-- Um veiculo = um equipamento Conta Litro instalado.
CREATE TABLE veiculo (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id            VARCHAR(64)  NOT NULL UNIQUE,   -- igual ao DEVICE_ID do Conta Litro
    placa                VARCHAR(10),
    modelo               VARCHAR(80),
    capacidade_tanque_l  DOUBLE PRECISION NOT NULL DEFAULT 45,
    meta_consumo_kml     DOUBLE PRECISION,               -- abaixo disso, consumo e considerado alto
    thingsboard_token    VARCHAR(120),                   -- token do device no ThingsBoard (opcional)
    equipamento_online   BOOLEAN NOT NULL DEFAULT FALSE,
    ultima_comunicacao   TIMESTAMP WITH TIME ZONE,
    criado_em            TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Uma viagem e um RECORTE do contador continuo do equipamento.
-- O Conta Litro acumula desde que liga; o backend guarda o valor no inicio
-- da viagem (colunas base_*) e a viagem e sempre "atual - base".
CREATE TABLE viagem (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    veiculo_id           BIGINT NOT NULL REFERENCES veiculo(id),
    status               VARCHAR(10) NOT NULL,            -- ABERTA | FECHADA
    inicio               TIMESTAMP WITH TIME ZONE NOT NULL,
    fim                  TIMESTAMP WITH TIME ZONE,
    ultima_leitura_em    TIMESTAMP WITH TIME ZONE NOT NULL,
    motivo_fechamento    VARCHAR(30),

    -- valores da viagem (ja descontada a base)
    distancia_km         DOUBLE PRECISION NOT NULL DEFAULT 0,
    combustivel_l        DOUBLE PRECISION NOT NULL DEFAULT 0,
    custo_brl            NUMERIC(10,2)    NOT NULL DEFAULT 0,  -- dinheiro em NUMERIC, nunca em ponto flutuante
    tempo_ocioso_s       DOUBLE PRECISION NOT NULL DEFAULT 0,
    aceleracoes_bruscas  INT NOT NULL DEFAULT 0,
    frenagens_bruscas    INT NOT NULL DEFAULT 0,
    nota_eficiencia      DOUBLE PRECISION,                -- ultima nota informada pelo equipamento

    -- valores absolutos do equipamento no momento em que a viagem abriu
    base_distancia_km    DOUBLE PRECISION NOT NULL DEFAULT 0,
    base_combustivel_l   DOUBLE PRECISION NOT NULL DEFAULT 0,
    base_custo_brl       NUMERIC(10,2)    NOT NULL DEFAULT 0,
    base_tempo_ocioso_s  DOUBLE PRECISION NOT NULL DEFAULT 0,
    base_aceleracoes     INT NOT NULL DEFAULT 0,
    base_frenagens       INT NOT NULL DEFAULT 0
);

-- Cada mensagem valida recebida do Conta Litro.
CREATE TABLE leitura (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    veiculo_id            BIGINT NOT NULL REFERENCES veiculo(id),
    viagem_id             BIGINT REFERENCES viagem(id),
    recebida_em           TIMESTAMP WITH TIME ZONE NOT NULL,  -- relogio do backend (sempre existe)
    instante_equipamento  TIMESTAMP WITH TIME ZONE,           -- campo ts do equipamento (pode vir nulo)
    velocidade_kmh        DOUBLE PRECISION NOT NULL,
    rpm                   INT NOT NULL,
    marcha                INT NOT NULL,
    tanque_pct            DOUBLE PRECISION NOT NULL,
    vazao_lph             DOUBLE PRECISION NOT NULL,
    consumo_kml           DOUBLE PRECISION,                   -- nulo com o veiculo parado
    ignicao               BOOLEAN NOT NULL,
    payload               TEXT NOT NULL                       -- mensagem original, para reprocessar depois
);

CREATE INDEX idx_leitura_veiculo_tempo ON leitura (veiculo_id, recebida_em);
CREATE INDEX idx_leitura_viagem        ON leitura (viagem_id);
CREATE INDEX idx_viagem_veiculo_status ON viagem  (veiculo_id, status);
